"""
Stage 3b: inject report_data.json into the HTML template and render RESULTS.md.

    python analysis/build_report.py
      -> out/results/ncd_burden_report.html   (the artifact page)
      -> analysis/results/RESULTS.md          (aggregates for the application text; committed)
      -> analysis/results/*.json|csv          (aggregates; committed)
"""

from __future__ import annotations

import json
import shutil
import sys
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
RES = HERE.parent / "out" / "results"
PUB = HERE / "results"


def f1(x):
    return "–" if x is None or (isinstance(x, float) and pd.isna(x)) else f"{x:.1f}"


def main() -> int:
    data = (RES / "report_data.json").read_text(encoding="utf-8")
    tpl = (HERE / "report_template.html").read_text(encoding="utf-8")
    html = tpl.replace("__DATA__", data.replace("</", "<\\/"))
    (RES / "ncd_burden_report.html").write_text(html, encoding="utf-8")
    print("html", (RES / "ncd_burden_report.html").stat().st_size, "bytes")

    PUB.mkdir(exist_ok=True)
    for name in ["summary.json", "report_data.json", "prevalence.csv", "prevalence_by_age_sex.csv", "pairwise_associations.csv", "rates_by_year.csv",
                 "condition_accrual.csv", "spearman.csv", "spearman_partial_age_sex.csv", "spearman_n.csv"]:
        shutil.copy(RES / name, PUB / name)

    D = json.loads(data)
    pop, H, C, K, MM, PR, FP, CI = D["population"], D["headline"], D["cascade"], D["ckm"], D["multimorbidity"], D["progression"], D["fatty_liver_progression"], D["ckd_incidence"]
    L = []
    L.append("# NCD burden across the Anubhav Life Care network, 2022-10-29 to 2026-10-29\n")
    L.append("Aggregates only. Generated by `etl-ncd/analysis/` from the AKTIV database; see the HTML report for charts and the methods section for definitions.\n")
    L.append("## Population\n")
    L.append(f"- {pop['bills']:,} visits linked into {pop['persons_total']:,} people ({pop['adults']:,} adults, {pop['children_under18']:,} children); {pop['numeric_results']:,} numeric results, {pop['usg_reports']:,} ultrasound reports, {pop['echo_reports']:,} echocardiograms.")
    L.append(f"- Adults: median age {pop['adult_median_age']:.0f}, {pop['adult_female_pct']:.1f}% women; {pop['adults_with_2plus_visits']:,} seen more than once, {pop['adults_followed_1yr_plus']:,} followed ≥ 1 year.")
    L.append(f"- {H['adults_tested_any_domain']:,} adults tested in ≥ 1 of 7 domains; {H['adults_with_any_condition']:,} ({H['pct_any_condition_among_tested']:.1f}%) have ≥ 1 chronic condition.\n")
    L.append("## Prevalence among tested adults, by category\n")
    L.append("| Category | Condition | Tested | Positive | Prevalence % (95% CI) | Age-sex standardised % |\n|---|---|---:|---:|---:|---:|")
    for cat in D["prevalence"]:
        for r in cat["rows"]:
            L.append(f"| {cat['category']} | {r['condition']} | {r['tested']:,} | {r['positive']:,} | {f1(r['prevalence_pct'])} ({f1(r['ci_low'])}–{f1(r['ci_high'])}) | {f1(r['age_sex_standardised_pct'])} |")
    L.append("\n## Cardio-kidney-metabolic (CKM) staging\n")
    L.append(f"{K['n_evaluable']:,} adults evaluable. Stage distribution: " + ", ".join(f"stage {s}: {K['stage_pct'][s]:.1f}%" for s in ["0", "1", "2", "3", "4"]) + ".")
    L.append("Stage 2+ by age band: " + ", ".join(f"{b}: {sum(K['by_age_pct'][b].get(s, 0) for s in ['2', '3', '4']):.1f}%" for b in ["18-29", "30-44", "45-59", "60-74", "75+"]) + ".")
    x = K["echo_cross"]
    L.append(f"Among adults with an echo: structural heart disease {x['shd_pct_if_dm']:.1f}% if diabetes vs {x['shd_pct_if_no_dm_tested']:.1f}% without; {x['shd_pct_if_ckd']:.1f}% if eGFR < 60 vs {x['shd_pct_if_no_ckd_tested']:.1f}%; LV hypertrophy {x['lvh_pct_if_ckd']:.1f}% if eGFR < 60 vs {x['lvh_pct_if_no_ckd_tested']:.1f}%.\n")
    L.append("## Condition network (age-sex adjusted odds ratios, adults tested for both)\n")
    L.append("Communities: " + "; ".join(f"**{n}**: {', '.join(c)}" for n, c in zip(D["network"]["community_names"], D["network"]["communities"])) + ".\n")
    L.append("Hubs (weighted degree): " + ", ".join(f"{n['node']} ({n['weighted_degree']:.1f}, {n['degree']} links)" for n in D["network"]["centrality"]) + ".\n")
    L.append("| A | B | P(B given A) % | P(B given not A) % | RR | aOR (95% CI) | n tested for both |\n|---|---|---:|---:|---:|---:|---:|")
    for l in D["top_links"][:20]:
        L.append(f"| {l['a']} | {l['b']} | {l['p_b_given_a']:.1f} | {l['p_b_given_not_a']:.1f} | {l['rr']:.2f} | {l['adj_or']:.2f} ({l['lo']:.2f}–{l['hi']:.2f}) | {l['n']:,} |")
    L.append("\n## Within each individual\n")
    m3 = MM["min_tested_3"]
    L.append(f"Adults tested in ≥ 3 of 9 domains (n = {m3['persons']:,}): " + ", ".join(f"{k} condition(s): {v:.1f}%" for k, v in m3["pct"].items()) + ".")
    L.append("Two or more conditions by age: " + ", ".join(f"{b}: {v['two_plus_pct']:.1f}%" for b, v in m3["by_age"].items()) + ".")
    L.append("Most common combinations: " + "; ".join(f"{c} ({n:,})" for c, n in MM["top_combinations"][:10]) + ".")
    L.append("Given a condition, mean number of other conditions: " + ", ".join(f"{k}: {v['mean_other_conditions']:.2f} (n {v['n']:,})" for k, v in MM["given_condition"].items()) + ".\n")
    L.append("## Progression within the same person\n")
    L.append(f"- Fasting glucose, prediabetic at first test (n {PR['fbs']['prediabetic_first_n']:,}): {PR['fbs']['pre_to_diabetic_range_pct']:.1f}% diabetic range at latest ({PR['fbs']['pre_to_diabetic_rate_per_100py']:.1f} per 100 person-years), {PR['fbs']['pre_reverted_to_normal_pct']:.1f}% reverted to normal. Normal at first (n {PR['fbs']['normal_first_n']:,}): {PR['fbs']['normal_to_prediabetic_pct']:.1f}% prediabetic, {PR['fbs']['normal_to_diabetic_range_pct']:.1f}% diabetic at latest.")
    L.append(f"- HbA1c repeated (n {PR['hba1c']['persons_repeat']:,}, median gap {PR['hba1c']['median_gap_years']:.1f} y): {PR['hba1c']['worsened_0.5_pct']:.1f}% rose ≥ 0.5, {PR['hba1c']['improved_0.5_pct']:.1f}% fell ≥ 0.5; {PR['hba1c']['still_uncontrolled_among_first_uncontrolled_pct']:.1f}% of those ≥ 8% stayed ≥ 8%.")
    L.append(f"- eGFR slope (n {PR['egfr']['persons_slope']:,}, median follow-up {PR['egfr']['median_followup_years']:.1f} y): median {PR['egfr']['median_slope']:.1f} mL/min/1.73m² per year; {PR['egfr']['rapid_decline_pct(<=-5/yr)']:.1f}% rapid decliners; {PR['egfr']['new_ckd_pct(first>=60,last<60)']:.1f}% crossed below 60; {PR['egfr']['ckd_persisted_pct(first<60,last<60)']:.1f}% of those < 60 stayed < 60.")
    for k, g in CI["groups"].items():
        ir = CI["irr"].get(k)
        L.append(f"- New eGFR < 60 among {k}: {g['events']} events / {g['person_years']:.0f} person-years = {g['rate_per_100py']:.1f} per 100 py" + (f", rate ratio {ir['irr_vs_no_diabetes']:.2f} ({ir['lo']:.2f}–{ir['hi']:.2f}) vs no diabetes" if ir else " (reference)") + ".")
    L.append(f"- Repeat liver ultrasound ≥ 6 months apart (n {FP['persons_repeat_usg']:,}): {FP['progressed_pct']:.1f}% progressed, {FP['regressed_pct']:.1f}% regressed; {FP['new_fatty_liver_pct(first 0, last >=1)']:.1f}% of normal livers (n {FP['n_first_normal']:,}) became fatty.")
    L.append(f"- Subclinical hypothyroidism (n {PR['tsh']['subclinical_first_n']:,}): {PR['tsh']['sub_to_overt_pct(>10)']:.1f}% became overt, {PR['tsh']['sub_persisted_pct']:.1f}% persisted, {PR['tsh']['sub_normalised_pct']:.1f}% normalised.")
    L.append(f"- Triglycerides normal → ≥ 150: {PR['tg']['rose_to_high_pct(first<150,last>=150)']:.1f}%; ALT normal → raised: {PR['alt']['normal_to_raised_pct(first<=40,last>40)']:.1f}%; haemoglobin fell ≥ 1 g/dL: {PR['hb']['fell_1g_pct']:.1f}%.\n")
    L.append("New conditions acquired during follow-up (negative in first 180 days, retested later, followed ≥ 1 year):\n")
    L.append("| Condition | Negative early | New positive later | % |\n|---|---:|---:|---:|")
    for a in sorted(D["accrual"], key=lambda r: -r["new_positive_pct"]):
        L.append(f"| {a['condition']} | {a['negative_early']:,} | {a['new_positive_later']:,} | {a['new_positive_pct']:.1f} |")
    L.append("\n## Care gaps\n")
    L.append(f"- Adults with diabetes (n {C['dm_n']:,}): ever tested HbA1c {C['dm_with_hba1c_pct']:.1f}%, creatinine {C['dm_egfr_tested_pct']:.1f}%, urine ACR {C['dm_acr_tested_pct']:.1f}%, lipids {C['dm_lipid_tested_pct']:.1f}%, liver USG {C['dm_usg_liver_pct']:.1f}%, echo {C['dm_echo_pct']:.1f}%.")
    L.append(f"- Where tested: eGFR < 60 in {C['dm_ckd_pct_among_egfr_tested']:.1f}%, albuminuria in {C['dm_albuminuria_pct_among_acr_tested']:.1f}%, fatty liver in {C['dm_fatty_pct_among_usg']:.1f}% (vs {D['cascade']['nonfatty_dm_pct_among_gly_tested']:.1f}% diabetes among non-fatty livers).")
    L.append(f"- Glycaemic control (latest HbA1c): " + ", ".join(f"{k}: {v:.1f}%" for k, v in C["dm_hba1c_control_dist_pct"].items()) + f"; LDL ≥ 70 in {C['dm_ldl_above70_pct']:.1f}%.")
    L.append(f"- People with eGFR < 60 (n {C['ckd_n']:,}): ACR ever {C['ckd_with_acr_pct']:.1f}%; anaemia {C['ckd_anaemia_pct']:.1f}% vs {C['nonckd_anaemia_pct']:.1f}% with preserved eGFR; G-stage distribution {C['ckd_g_stage_dist']}.")
    L.append(f"- Fatty liver (n {C['fatty_n']:,}, grades {C['fatty_grade_dist']}): LFT ever {C['fatty_with_lft_pct']:.1f}%; transaminitis {C['fatty_transaminitis_pct']:.1f}% where tested; FIB-4 indeterminate/high {C['fatty_fib4_indet_plus_pct']:.1f}%.\n")
    L.append("## Volume-adjusted rates per 1,000 tested adults by year\n")
    yr = pd.DataFrame(D["rates_by_year"])
    cols = ["Diabetes", "Dyslipidaemia", "CKD (eGFR<60)", "Fatty liver", "Hypothyroid", "Anaemia", "Structural heart dis."]
    L.append("| Year | Adults seen | " + " | ".join(cols) + " |\n|---|---:|" + "---:|" * len(cols))
    for _, y in yr.iterrows():
        L.append(f"| {int(y.year)} | {int(y.adults_seen):,} | " + " | ".join(f"{y[c + ' per 1000 tested']:.0f}" for c in cols) + " |")
    (PUB / "RESULTS.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("wrote", PUB / "RESULTS.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
